  function detectLang() {
    const qp = new URLSearchParams(location.search).get('lang');
    if (qp === 'zh' || qp === 'en') return qp;
    const saved = localStorage.getItem('xd-lang');
    if (saved === 'zh' || saved === 'en') return saved;
    const nav = (navigator.language || '').toLowerCase();
    return nav.startsWith('zh') ? 'zh' : 'en';
  }

  let current = detectLang();

  function t(key, vars) {
    const table = DICT[current] || DICT.zh;
    let str = table[key] ?? DICT.zh[key] ?? key;
    if (vars) {
      str = str.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? String(vars[k]) : `{${k}}`));
    }
    return str;
  }

  function applyDom(root = document) {
    root.querySelectorAll('[data-i18n]').forEach((el) => {
      el.textContent = t(el.dataset.i18n);
    });
    root.querySelectorAll('[data-i18n-html]').forEach((el) => {
      el.innerHTML = t(el.dataset.i18nHtml);
    });
    root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
      el.placeholder = t(el.dataset.i18nPlaceholder);
    });
    root.querySelectorAll('[data-i18n-title]').forEach((el) => {
      el.title = t(el.dataset.i18nTitle);
    });
    root.querySelectorAll('[data-i18n-aria]').forEach((el) => {
      el.setAttribute('aria-label', t(el.dataset.i18nAria));
    });
    const tpl = root.getElementById ? root.getElementById('tpl-task') : null;
    if (tpl && tpl.content) applyDom(tpl.content);
  }

  function setLang(lang) {
    if (lang !== 'zh' && lang !== 'en') return current;
    current = lang;
    localStorage.setItem('xd-lang', lang);
    document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
    applyDom(document);
    return current;
  }

  document.documentElement.lang = current === 'zh' ? 'zh-CN' : 'en';

  window.XD_I18N = {
    t,
    getLang: () => current,
    setLang,
    applyDom,
  };
